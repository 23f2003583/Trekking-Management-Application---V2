<template>
  <div>
    <h2>My Managed Treks Summary</h2>
    <div v-if="summary">
      <p>Total Bookings on My Treks: {{ summary.total_bookings }}</p>
      <p>Active Bookings: {{ summary.active_bookings }}</p>
      <p>Completed Bookings: {{ summary.completed_bookings }}</p>
      <p>Revenue Generated by My Treks: ₹{{ summary.total_revenue }}</p>
      
      <div v-if="summary.trek_names && summary.trek_names.length > 0">
        <h3>Bookings Breakdown by Trek</h3>
        <Bar :data="countChartData" :options="{ responsive: true }" />
      </div>
    </div>
  </div>
</template>

<script>
import axios from 'axios'
import {
  Chart as ChartJS,
  Title,
  Tooltip,
  Legend,
  BarElement,
  CategoryScale,
  LinearScale,
} from 'chart.js'
import { Bar } from 'vue-chartjs'

ChartJS.register(CategoryScale, LinearScale, BarElement, Title, Tooltip, Legend)

export default {
  name: 'StaffSummary',
  components: { Bar },
  data() {
    return {
      summary: {},
    }
  },
  computed: {
    countChartData() {
      return {
        labels: this.summary.trek_names || [],
        datasets: [
          {
            label: 'Bookings Managed',
            data: this.summary.trek_counts || [],
            backgroundColor: 'rgba(255, 159, 64, 0.5)',
          },
        ],
      }
    },
  },
  methods: {
    async fetchSummary() {
      try {
        const token = localStorage.getItem('staff_token')
        const response = await axios.get('http://localhost:5000/api/staff/summary', {
          headers: {
            Authorization: `Bearer ${token}`,
          },
        })
        this.summary = response.data
        console.log("Staff Summary:", this.summary)
      } catch (error) {
        console.error('Error fetching staff summary:', error)
      }
    },
  },
  mounted() {
    this.fetchSummary()
  },
}
</script>